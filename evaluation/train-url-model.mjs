











import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadDatasets } from './dataset.mjs'
import { URL_MODEL_DIMENSION, urlLexicalFeatures } from '../backend/services/urlLexicalFeatures.js'

const [datasetPath, outputPath = 'backend/services/urlLexicalModel.js'] = process.argv.slice(2)
if (!datasetPath) throw new Error('Usage: node evaluation/train-url-model.mjs <dataset.jsonl> [output.js]')
const rows = loadDatasets([datasetPath]).filter((row) => row.kind === 'url' && row.split === 'tuning')
if (rows.length < 100 || !rows.some((row) => row.label === 'phishing') || !rows.some((row) => row.label === 'legitimate')) {
  throw new Error('Training requires at least 100 labeled tuning URLs from both classes')
}

const samples = rows.map((row) => {
  const indices = urlLexicalFeatures(row.input)
  return { indices, scale: 1 / Math.sqrt(Math.max(1, indices.length)), label: row.label === 'phishing' ? 1 : 0 }
})
const weights = new Float64Array(URL_MODEL_DIMENSION)
let bias = 0
const learningRate = 0.8
const regularization = 0.002
for (let epoch = 0; epoch < 450; epoch += 1) {
  const gradient = new Float64Array(URL_MODEL_DIMENSION)
  let biasGradient = 0
  for (const sample of samples) {
    let logit = bias
    for (const index of sample.indices) logit += weights[index] * sample.scale
    const probability = logit >= 35 ? 1 : logit <= -35 ? 0 : 1 / (1 + Math.exp(-logit))
    const error = probability - sample.label
    biasGradient += error
    for (const index of sample.indices) gradient[index] += error * sample.scale
  }
  const rate = learningRate / Math.sqrt(1 + epoch / 30)
  bias -= rate * biasGradient / samples.length
  for (let index = 0; index < weights.length; index += 1) {
    weights[index] -= rate * (gradient[index] / samples.length + regularization * weights[index])
  }
}

function probability(sample) {
  let logit = bias
  for (const index of sample.indices) logit += weights[index] * sample.scale
  return logit >= 35 ? 1 : logit <= -35 ? 0 : 1 / (1 + Math.exp(-logit))
}
const predictions = samples.map((sample) => ({ ...sample, probability: probability(sample) }))
function chooseThreshold(maximumFalsePositiveRate, minimum = 0.5) {
  const candidates = [...new Set(predictions.map((item) => item.probability))].filter((value) => value >= minimum).sort((a, b) => a - b)
  let best = { threshold: 1, recall: 0, fpr: 0 }
  for (const threshold of candidates) {
    const phishing = predictions.filter((item) => item.label === 1)
    const legitimate = predictions.filter((item) => item.label === 0)
    const recall = phishing.filter((item) => item.probability >= threshold).length / phishing.length
    const fpr = legitimate.filter((item) => item.probability >= threshold).length / legitimate.length
    if (fpr <= maximumFalsePositiveRate && (recall > best.recall || (recall === best.recall && threshold > best.threshold))) {
      best = { threshold, recall, fpr }
    }
  }
  return best
}
const warning = chooseThreshold(0.01, 0.5)
const block = chooseThreshold(0, Math.max(0.8, warning.threshold))
const model = {
  schemaVersion: 1,
  dimension: URL_MODEL_DIMENSION,
  bias: Number(bias.toFixed(10)),
  weights: [...weights].map((value) => Number(value.toFixed(10))),
  warningThreshold: Number(warning.threshold.toFixed(10)),
  blockThreshold: Number(block.threshold.toFixed(10)),
  training: {
    source: 'UCI PhiUSIIL Phishing URL Dataset, DOI 10.1016/j.cose.2023.103545, CC BY 4.0',
    split: 'tuning only', rows: rows.length,
    warningRecall: Number(warning.recall.toFixed(6)), warningFpr: Number(warning.fpr.toFixed(6)),
    blockRecall: Number(block.recall.toFixed(6)), blockFpr: Number(block.fpr.toFixed(6)),
  },
}
const output = `// Generated by evaluation/train-url-model.mjs from the tuning split only.\nexport default ${JSON.stringify(model)}\n`
writeFileSync(resolve(outputPath), output, { flag: 'w' })
console.log(JSON.stringify({ output: resolve(outputPath), ...model.training, warningThreshold: model.warningThreshold, blockThreshold: model.blockThreshold }))
